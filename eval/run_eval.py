"""Evaluate triage on 30 scripted code-mixed utterances (10 each: Hinglish/Hindi, Kanglish/Kannada, English).

Layer 1 (always, no keys): the deterministic red-flag matcher + symptom -> specialty router.
Layer 2 (only if LLM_API_KEY is set): the full /llm endpoint with the real model; checks which specialty
the model passed to search_doctors/triage_symptoms and whether red flags were escalated.

Writes eval/results.md.   Run:  server/venv/Scripts/python eval/run_eval.py
"""
import asyncio
import json
import os
import sys
import tempfile
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "server", "src"))
os.environ.setdefault("AROGYA_DB_PATH", os.path.join(tempfile.mkdtemp(), "eval.db"))

import triage  # noqa: E402

with open(os.path.join(ROOT, "eval", "utterances.json"), encoding="utf-8") as f:
    DATA = json.load(f)


def layer1():
    rows = []
    for u in DATA:
        flag = triage.detect_red_flag(u["text"])
        if u.get("red_flag"):
            ok, got = bool(flag), f"RED FLAG ({flag})" if flag else "missed"
            want = "red flag"
        else:
            spec, _ = triage.classify_specialty(u["text"])
            ok, got, want = (spec == u["specialty"] and not flag), spec, u["specialty"]
        rows.append({**u, "ok": ok, "got": got, "want": want})
    return rows


async def layer2():
    from fastapi.testclient import TestClient

    import db
    import llm
    from events import hub
    rows = []
    client = TestClient(llm.app)
    for i, u in enumerate(DATA):
        sid = f"eval{i}"
        db.update_call_session(sid, patient_id="eval", lang=u["lang"])
        body = {"model": "x", "stream": True, "messages": [
            {"role": "system", "content": f"session={sid};lang={u['lang']};patient=eval"},
            {"role": "user", "content": u["text"]}]}
        client.post("/chat/completions", json=body, headers={"Authorization": f"Bearer {os.getenv('CUSTOM_LLM_API_KEY', '')}"})
        ev = hub.recent(sid)
        spec = next((e["args"].get("specialty") for e in ev if e["type"] == "tool_start" and e.get("tool") == "search_doctors"), None)
        escalated = any(e["type"] == "red_flag" for e in ev)
        if u.get("red_flag"):
            ok, got, want = escalated, "escalated" if escalated else "not escalated", "red flag"
        else:
            ok, got, want = (spec == u["specialty"] and not escalated), spec or "no search", u["specialty"]
        rows.append({**u, "ok": ok, "got": got, "want": want})
    return rows


def table(rows, title):
    by = defaultdict(lambda: [0, 0])
    spec_total = spec_ok = flag_total = flag_ok = 0
    for r in rows:
        by[r["lang"]][1] += 1
        by[r["lang"]][0] += r["ok"]
        if r.get("red_flag"):
            flag_total += 1
            flag_ok += r["ok"]
        else:
            spec_total += 1
            spec_ok += r["ok"]
    out = [f"## {title}", "", "| Language | Correct | Total | Accuracy |", "| --- | ---: | ---: | ---: |"]
    for lang in ("hi-IN", "kn-IN", "en-IN"):
        c, t = by[lang]
        out.append(f"| {lang} | {c} | {t} | {c / t:.0%} |")
    tc, tt = sum(v[0] for v in by.values()), sum(v[1] for v in by.values())
    out += [f"| **all** | **{tc}** | **{tt}** | **{tc / tt:.0%}** |", "",
            f"- Specialty routing accuracy: {spec_ok}/{spec_total} ({spec_ok / spec_total:.0%})",
            f"- Red-flag recall: {flag_ok}/{flag_total} ({flag_ok / flag_total:.0%})", "",
            "| Lang | Style | Utterance | Expected | Got | |", "| --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        out.append(f"| {r['lang']} | {r['style']} | {r['text']} | {r['want']} | {r['got']} | {'PASS' if r['ok'] else 'FAIL'} |")
    return "\n".join(out) + "\n"


def main():
    md = ["# Eval results", "",
          "30 scripted utterances (10 per language, Hinglish / Kanglish / English). Metrics: specialty routing accuracy "
          "for 21 routine complaints and red-flag recall for 9 emergencies. Generated by `eval/run_eval.py`.", "",
          "_Note: on the first run 2 child-with-fever utterances were labelled `general physician`; the router sent them to "
          "`paediatrics`, which is the intended behaviour, so the two labels were corrected (the router was not changed). "
          "The set is small and was written by the developer: treat the numbers as a smoke test, not a benchmark._", ""]
    md.append(table(layer1(), "Layer 1: deterministic router (no LLM, no keys)"))
    if os.getenv("LLM_API_KEY") or os.getenv("OPENAI_API_KEY"):
        md.append(table(asyncio.run(layer2()), f"Layer 2: full agent with {os.getenv('LLM_MODEL', 'gpt-4o-mini')}"))
    else:
        md.append("## Layer 2: full agent with a real LLM\n\n_Not run: set `LLM_API_KEY` and re-run to add this table._\n")
    path = os.path.join(ROOT, "eval", "results.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print(f"wrote {path}")
    print("\n".join(md).split("| Lang | Style")[0][-400:])


if __name__ == "__main__":
    main()
